//! The built-in skins and fonts are folders shipped beside the executable
//! (`src/shipped.rs`), not part of the binary. This script:
//!
//! * tells a development build where the source tree keeps them, so `cargo
//!   run` and the tests work without packaging. A packaged build
//!   (`NANATYPE_REQUIRE_RESOURCES=1`) ships its own copies and must not fall
//!   back to the build machine's;
//! * embeds the default skin alone, so the app still opens when the skins
//!   folder is gone.

use std::fmt::Write as _;
use std::path::Path;
use std::{env, fs};

/// `builtin/<this>` is `registry::DEFAULT_SKIN` (a test checks the id).
const DEFAULT_SKIN_DIR: &str = "halo";

fn main() {
    let root = env::var("CARGO_MANIFEST_DIR").expect("cargo sets CARGO_MANIFEST_DIR");
    let root = Path::new(&root);
    println!("cargo:rerun-if-env-changed=NANATYPE_REQUIRE_RESOURCES");
    if env::var("NANATYPE_REQUIRE_RESOURCES").as_deref() != Ok("1") {
        for (name, dir) in [
            ("NANATYPE_SOURCE_SKINS", "builtin"),
            ("NANATYPE_SOURCE_FONTS", "fonts"),
        ] {
            println!("cargo:rustc-env={name}={}", root.join(dir).display());
        }
    }
    embed_default_skin(&root.join("builtin").join(DEFAULT_SKIN_DIR));
}

fn embed_default_skin(dir: &Path) {
    println!("cargo:rerun-if-changed=builtin/{DEFAULT_SKIN_DIR}");
    // Dotfiles and SVG design masters stay in the repository: skins only
    // load their rendered PNGs.
    fn walk(root: &Path, dir: &Path, files: &mut Vec<String>) {
        for entry in fs::read_dir(dir).expect("read the default skin") {
            let entry = entry.expect("package entry");
            let name = entry.file_name().to_string_lossy().to_ascii_lowercase();
            if name.starts_with('.') || name.ends_with(".svg") {
                continue;
            }
            let ty = entry.file_type().unwrap();
            assert!(!ty.is_symlink(), "package resources cannot be symlinks");
            if ty.is_dir() {
                walk(root, &entry.path(), files);
            } else if ty.is_file() {
                let path = entry.path();
                let path = path.strip_prefix(root).unwrap().to_str().unwrap();
                files.push(path.replace('\\', "/"));
            }
        }
    }
    let mut files = Vec::new();
    walk(dir, dir, &mut files);
    files.sort();
    let mut out = String::from(
        "// @generated by build.rs from the default built-in skin.\n\
         static EMBEDDED_DEFAULT: &[(&str, &[u8])] = &[\n",
    );
    for path in files {
        let _ = writeln!(
            out,
            "    ({path:?}, include_bytes!({:?})),",
            dir.join(&path).display().to_string()
        );
    }
    out.push_str("];\n");
    let dest = Path::new(&env::var("OUT_DIR").expect("cargo sets OUT_DIR")).to_path_buf();
    fs::write(dest.join("embedded_default.rs"), out).expect("write embedded_default.rs");
}
